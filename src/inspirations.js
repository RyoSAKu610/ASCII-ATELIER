export function trailIndex(index) {
  const length = MASTERPIECE_TRAIL.length
  return ((Number(index) || 0) % length + length) % length
}

export function getTrailEntry(index) {
  return MASTERPIECE_TRAIL[trailIndex(index)]
}

export function randomTrailIndex(seed = Date.now(), currentIndex = -1) {
  const random = mulberry32(hashText(`trail|${seed}|${currentIndex}`))
  if (MASTERPIECE_TRAIL.length < 2) return 0
  let next = Math.floor(random() * MASTERPIECE_TRAIL.length)
  if (next === currentIndex) next = (next + 1) % MASTERPIECE_TRAIL.length
  return next
}

export function makeStudyPrompt(entry = MASTERPIECE_TRAIL[0], seed = 0) {
  const random = mulberry32(hashText(`${entry.id}|study|${seed}`))
  const subject = pick(entry.subjects, random)
  const mood = pick(entry.moods, random)
  const technique = pick(TECHNIQUES, random)
  const composition = pick(COMPOSITIONS, random)
  return `${subject}を、${entry.title}研究として${mood}、${technique}${composition}`
}

export function makeSamplePrompt(seed = Date.now(), baseEntry = null) {
  const entry = baseEntry || getTrailEntry(seed)
  const random = mulberry32(hashText(`${entry.id}|sample|${seed}`))
  const subjectPool = random() > 0.42 ? entry.subjects : EXTRA_SUBJECTS
  const subject = pick(subjectPool, random)
  const mood = pick([...entry.moods, ...TECHNIQUES], random)
  const composition = pick(COMPOSITIONS, random)
  const extra = pick(TECHNIQUES, random)
  const prompt = `${subject}を${mood}、${extra}${composition}`

  return {
    prompt,
    sourceId: entry.id,
    sourceTitle: entry.title,
    sourceRank: entry.rank,
    note: entry.lesson,
    seed,
    options: {
      width: entry.width,
      height: entry.height,
      density: entry.density,
      contrast: entry.contrast,
      craft: entry.craft,
      style: entry.style,
      seedShift: hashText(`${entry.id}|${seed}`) % 10000,
    },
    palette: entry.palette,
  }
}

export function makeInfiniteSamples(count = 3, seed = Date.now(), entry = null) {
  return Array.from({ length: count }, (_, index) => makeSamplePrompt(Number(seed) + index * 7919, entry))
}

function pick(items, random) {
  return items[Math.floor(random() * items.length) % items.length]
}

function hashText(value = '') {
  let hash = 2166136261
  for (const char of String(value)) {
    hash ^= char.codePointAt(0)
    hash = Math.imul(hash, 16777619)
  }
  return hash >>> 0
}

function mulberry32(seed) {
  let value = seed >>> 0
  return () => {
    value += 0x6D2B79F5
    let next = value
    next = Math.imul(next ^ (next >>> 15), next | 1)
    next ^= next + Math.imul(next ^ (next >>> 7), next | 61)
    return ((next ^ (next >>> 14)) >>> 0) / 4294967296
  }
}
